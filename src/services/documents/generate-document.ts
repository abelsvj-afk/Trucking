// Document generation (docs/design/expense-buckets-documents.md
// section 3): the seam a document backend plugs into. A generator
// turns a document model (lib/document-templates.ts) into file bytes.
// The default generator, "app_pdf", renders in-app with the
// dependency-free PDF writer (lib/simple-pdf.ts) - no external
// service, no account, works offline.
//
// A free Google-Docs-type backend can be added later as a second
// generator behind THIS interface (selected per call), without
// touching the filing pipeline or the callers. It is deliberately NOT
// wired to any live Google account in this build: GENERATORS is the
// whole registry, and asking for an unregistered generator fails
// honestly instead of faking a document.

import type { SupabaseClient } from "@supabase/supabase-js";
import type { Document } from "@/types/entities";
import { renderPdf, type PdfTextBlock } from "@/lib/simple-pdf";
import { documentModelToText, type DocumentModel } from "@/lib/document-templates";
import { storeDocumentFile } from "./store-document";

export interface GeneratedFile {
  bytes: Uint8Array;
  contentType: string;
  /** File extension, no dot. */
  extension: string;
}

export interface DocumentGenerator {
  id: string;
  label: string;
  render(model: DocumentModel): GeneratedFile;
}

export const APP_PDF_GENERATOR_ID = "app_pdf";

export const appPdfGenerator: DocumentGenerator = {
  id: APP_PDF_GENERATOR_ID,
  label: "Created in the app (PDF)",
  render(model) {
    const blocks: PdfTextBlock[] = [{ text: model.title, size: 17, bold: true, spaceBefore: 0 }];
    for (const section of model.sections) {
      if (section.heading) blocks.push({ text: section.heading, size: 13, bold: true, spaceBefore: 14 });
      for (const line of section.lines) blocks.push({ text: line, size: 11, spaceBefore: 2 });
    }
    blocks.push({ text: "Generated by Road to Legacy from the records above.", size: 9, spaceBefore: 18 });
    return { bytes: renderPdf(blocks), contentType: "application/pdf", extension: "pdf" };
  },
};

/** The generator registry. Future backends register here; nothing else changes. */
export const GENERATORS: Record<string, DocumentGenerator> = {
  [APP_PDF_GENERATOR_ID]: appPdfGenerator,
};

export function getGenerator(id: string | undefined): DocumentGenerator | null {
  return GENERATORS[id ?? APP_PDF_GENERATOR_ID] ?? null;
}

function slug(text: string): string {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 48) || "document"
  );
}

export interface CreateDocumentInput {
  companyId: string;
  relatedEntityType: string;
  relatedEntityId: string;
  /** documents.doc_type the generated document files under. */
  docType: string;
  situation: string | null;
  model: DocumentModel;
  /** Generator id; default the in-app PDF generator. */
  generatorId?: string;
}

/**
 * Renders a document model and files it through the ONE storage
 * pipeline, attached to its record, marked source='generated' with
 * the generator named - so a created document lands in the same
 * Documents area, previewable like an upload, and visibly created.
 * Throws on an unknown generator or a storage failure.
 */
export async function createDocumentFile(client: SupabaseClient, input: CreateDocumentInput): Promise<Document> {
  const generator = getGenerator(input.generatorId);
  if (!generator) {
    throw new Error(
      `Document generator "${input.generatorId}" is not available. Available: ${Object.keys(GENERATORS).join(", ")}.`,
    );
  }
  const file = generator.render(input.model);
  const fileName = `${slug(input.model.title)}.${file.extension}`;
  return storeDocumentFile(client, {
    companyId: input.companyId,
    relatedEntityType: input.relatedEntityType,
    relatedEntityId: input.relatedEntityId,
    fileName,
    body: new Blob([file.bytes.buffer as ArrayBuffer], { type: file.contentType }),
    contentType: file.contentType,
    size: file.bytes.byteLength,
    docType: input.docType,
    situation: input.situation,
    source: "generated",
    generator: generator.id,
    // Phase 3 (§2.3): store the model itself — the one source the Page
    // face renders from. Tolerated absent until 00088 is applied.
    model: input.model,
    // The document's own text rides along as its searchable content.
    caption: documentModelToText(input.model).join(" "),
  });
}
